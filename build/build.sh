#!/usr/bin/env bash
# Builds TypePaste and "TypePaste Setup.exe" on Linux (or macOS/WSL) with the .NET 10 SDK and NSIS (makensis).
#
#   ./build/build.sh            # test, publish, create installer
#   SKIP_TESTS=1 ./build/build.sh
#
# Output: artifacts/publish/ (the app) and "artifacts/TypePaste Setup.exe".
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

VERSION="$(sed -n 's:.*<Version>\(.*\)</Version>.*:\1:p' Directory.Build.props | head -n1)"
PUBLISH_DIR="$ROOT/artifacts/publish"
GENERATED="$ROOT/installer/generated"

command -v dotnet >/dev/null || { echo "error: the .NET 10 SDK (dotnet) is required" >&2; exit 1; }
command -v makensis >/dev/null || { echo "error: NSIS (makensis) is required, e.g. 'apt install nsis'" >&2; exit 1; }

echo "==> TypePaste $VERSION"

if [[ "${SKIP_TESTS:-0}" != "1" ]]; then
  echo "==> Running unit tests"
  dotnet test tests/TypePaste.Core.Tests -c Release --nologo
fi

echo "==> Publishing self-contained win-x64 build"
rm -rf "$PUBLISH_DIR"
dotnet publish src/TypePaste/TypePaste.csproj -c Release -r win-x64 --self-contained true \
  -p:DebugType=none -p:DebugSymbols=false -o "$PUBLISH_DIR" --nologo

test -f "$PUBLISH_DIR/TypePaste.exe" || { echo "error: TypePaste.exe was not produced" >&2; exit 1; }

echo "==> Generating installer file lists"
mkdir -p "$GENERATED"
python3 - "$PUBLISH_DIR" "$GENERATED" <<'PY'
import os, sys
publish, generated = sys.argv[1], sys.argv[2]
files, dirs = [], []
for base, subdirs, names in os.walk(publish):
    subdirs.sort()
    rel = os.path.relpath(base, publish)
    rel = "" if rel == "." else rel.replace("/", "\\")
    if rel:
        dirs.append(rel)
    for name in sorted(names):
        files.append((rel, name, os.path.join(base, name)))

with open(os.path.join(generated, "install_files.nsh"), "w", encoding="utf-8") as out:
    out.write("; Generated by build.sh - do not edit.\n")
    current = None
    for rel, name, full in files:
        if rel != current:
            out.write(f'SetOutPath "$INSTDIR{chr(92) + rel if rel else ""}"\n')
            current = rel
        out.write(f'File "{full}"\n')
    out.write('SetOutPath "$INSTDIR"\n')

with open(os.path.join(generated, "uninstall_files.nsh"), "w", encoding="utf-8") as out:
    out.write("; Generated by build.sh - do not edit. Removes exactly the installed files.\n")
    for rel, name, _ in files:
        path = f"{rel}\\{name}" if rel else name
        out.write(f'Delete "$INSTDIR\\{path}"\n')
    for rel in sorted(dirs, key=lambda d: d.count("\\"), reverse=True):
        out.write(f'RMDir "$INSTDIR\\{rel}"\n')
print(f"    {len(files)} files")
PY

# File list used by the end-to-end tests to verify that every runtime file was installed.
(cd "$PUBLISH_DIR" && find . -type f | sed 's#^\./##; s#/#\\#g' | LC_ALL=C sort) > "$ROOT/artifacts/publish-files.txt"

echo "==> Building installer"
makensis -V2 -INPUTCHARSET UTF8 -DVERSION="$VERSION" -DPUBLISH_DIR="$PUBLISH_DIR" \
  "-DOUTPUT_FILE=$ROOT/artifacts/TypePaste Setup.exe" installer/TypePaste.nsi

ls -la "$ROOT/artifacts/TypePaste Setup.exe"
sha256sum "$ROOT/artifacts/TypePaste Setup.exe" | tee "$ROOT/artifacts/TypePaste Setup.exe.sha256"
echo "==> Done"
