<#
.SYNOPSIS
    Builds TypePaste and "TypePaste Setup.exe" on Windows.

.DESCRIPTION
    Requires the .NET 10 SDK and NSIS 3 (makensis.exe on PATH or in the default install folder).
    Output: artifacts\publish\ (the app) and "artifacts\TypePaste Setup.exe".

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File build\build.ps1
#>
param(
    [switch] $SkipTests
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$version = ([xml](Get-Content "$root\Directory.Build.props")).Project.PropertyGroup.Version | Select-Object -First 1
$publish = Join-Path $root 'artifacts\publish'
$generated = Join-Path $root 'installer\generated'

$makensis = (Get-Command makensis.exe -ErrorAction SilentlyContinue).Source
if (-not $makensis) {
    $makensis = @("${env:ProgramFiles(x86)}\NSIS\makensis.exe", "$env:ProgramFiles\NSIS\makensis.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
}
if (-not $makensis) { throw 'NSIS (makensis.exe) is required: https://nsis.sourceforge.io or "winget install NSIS.NSIS".' }

Write-Host "==> TypePaste $version"

if (-not $SkipTests) {
    Write-Host '==> Running unit tests'
    dotnet test tests\TypePaste.Core.Tests -c Release --nologo
    if ($LASTEXITCODE) { throw 'Unit tests failed.' }
}

Write-Host '==> Publishing self-contained win-x64 build'
if (Test-Path $publish) { Remove-Item $publish -Recurse -Force }
dotnet publish src\TypePaste\TypePaste.csproj -c Release -r win-x64 --self-contained true -p:DebugType=none -p:DebugSymbols=false -o $publish --nologo
if ($LASTEXITCODE) { throw 'Publish failed.' }

Write-Host '==> Generating installer file lists'
New-Item -ItemType Directory -Force $generated | Out-Null
$files = Get-ChildItem $publish -Recurse -File | Sort-Object FullName
$install = @('; Generated by build.ps1 - do not edit.')
$uninstall = @('; Generated by build.ps1 - do not edit. Removes exactly the installed files.')
$current = $null
foreach ($file in $files) {
    $relativeDir = $file.DirectoryName.Substring($publish.Length).TrimStart('\')
    if ($relativeDir -ne $current) {
        $install += if ($relativeDir) { "SetOutPath `"`$INSTDIR\$relativeDir`"" } else { 'SetOutPath "$INSTDIR"' }
        $current = $relativeDir
    }
    $install += "File `"$($file.FullName)`""
    $relative = $file.FullName.Substring($publish.Length).TrimStart('\')
    $uninstall += "Delete `"`$INSTDIR\$relative`""
}
$install += 'SetOutPath "$INSTDIR"'
Get-ChildItem $publish -Recurse -Directory | Sort-Object { $_.FullName.Length } -Descending | ForEach-Object {
    $uninstall += "RMDir `"`$INSTDIR\$($_.FullName.Substring($publish.Length).TrimStart('\'))`""
}
Set-Content -Encoding UTF8 (Join-Path $generated 'install_files.nsh') $install
Set-Content -Encoding UTF8 (Join-Path $generated 'uninstall_files.nsh') $uninstall
$files | ForEach-Object { $_.FullName.Substring($publish.Length).TrimStart('\') } | Set-Content -Encoding UTF8 (Join-Path $root 'artifacts\publish-files.txt')
Write-Host "    $($files.Count) files"

Write-Host '==> Building installer'
& $makensis /V2 /INPUTCHARSET UTF8 "/DVERSION=$version" "/DPUBLISH_DIR=$publish" "/DOUTPUT_FILE=$root\artifacts\TypePaste Setup.exe" installer\TypePaste.nsi
if ($LASTEXITCODE) { throw 'makensis failed.' }

$setup = Join-Path $root 'artifacts\TypePaste Setup.exe'
$hash = (Get-FileHash $setup -Algorithm SHA256).Hash.ToLowerInvariant()
"$hash  TypePaste Setup.exe" | Set-Content -Encoding ASCII "$setup.sha256"
Write-Host "==> Done: $setup ($([math]::Round((Get-Item $setup).Length / 1MB, 1)) MB)"
